package cinemasystem;

/**
 * Enum representing the different genres of movies in the cinema system.
 * <p>
 * This enum is used by the {@link Movie} class to categorize movies.
 * </p>
 */
public enum Genre {
    /** Action movies */
    ACTION,

    /** Comedy movies */
    COMEDY,

    /** Drama movies */
    DRAMA,

    /** Horror movies */
    HORROR,

    /** Romance movies */
    ROMANCE
}
